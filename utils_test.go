func TestParseEnvHelpers(t *testing.T) {
	t.Setenv("SM_TEST_INT", "42")
	if got := parseIntEnv("SM_TEST_INT", 0); got != 42 {
		t.Errorf("parseIntEnv = %d, want 42", got)
	}
	t.Setenv("SM_TEST_INT", "notanumber")
	if got := parseIntEnv("SM_TEST_INT", 7); got != 7 {
		t.Errorf("parseIntEnv invalid = %d, want 7", got)
	}
	if got := parseIntEnv("SM_TEST_MISSING", 7); got != 7 {
		t.Errorf("parseIntEnv missing = %d, want 7", got)
	}

	t.Setenv("SM_TEST_BOOL", "true")
	if !parseBoolEnv("SM_TEST_BOOL", false) {
		t.Error("parseBoolEnv = false, want true")
	}
	t.Setenv("SM_TEST_BOOL", "bogus")
	if !parseBoolEnv("SM_TEST_BOOL", true) {
		t.Error("parseBoolEnv invalid should fall back to default true")
	}

	t.Setenv("SM_TEST_DUR", "3s")
	if got := parseDurationEnv("SM_TEST_DUR", time.Second); got != 3*time.Second {
		t.Errorf("parseDurationEnv = %v, want 3s", got)
	}
	t.Setenv("SM_TEST_DUR", "xyz")
	if got := parseDurationEnv("SM_TEST_DUR", 4*time.Second); got != 4*time.Second {
		t.Errorf("parseDurationEnv invalid = %v, want 4s", got)
	}
}

