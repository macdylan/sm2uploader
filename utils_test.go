func TestPostProcessAndPostProcessToEquivalent(t *testing.T) {
	in := strings.NewReader(sampleGcode)

	out, err := postProcess(strings.NewReader(sampleGcode))
	if err != nil {
		t.Fatalf("postProcess: %v", err)
	}

	var buf bytes.Buffer
	if err := postProcessTo(&buf, in); err != nil {
		t.Fatalf("postProcessTo: %v", err)
	}
	if !bytes.Equal(out, buf.Bytes()) {
		t.Error("postProcess and postProcessTo outputs differ")
	}
}

func TestPostProcessMarksFixedFile(t *testing.T) {
	out, err := postProcess(strings.NewReader(sampleGcode))
	if err != nil {
		t.Fatalf("postProcess: %v", err)
	}
	if !bytes.Contains(out, []byte("; Postprocessed by smfix")) {
		t.Error("output missing smfix marker")
	}
	if len(out) == 0 {
		t.Error("output is empty")
	}
}

func TestPostProcessIdempotent(t *testing.T) {
	once, err := postProcess(strings.NewReader(sampleGcode))
	if err != nil {
		t.Fatalf("first pass: %v", err)
	}
	twice, err := postProcess(bytes.NewReader(once))
	if err != nil {
		t.Fatalf("second pass: %v", err)
	}
	// an already-fixed file takes the isFixed passthrough path, so from the
	// second pass on the output must be byte-stable
	third, err := postProcess(bytes.NewReader(twice))
	if err != nil {
		t.Fatalf("third pass: %v", err)
	}
	if !bytes.Equal(twice, third) {
		t.Error("postProcess is not stable for already-fixed files")
	}
	if !bytes.Contains(twice, []byte("; Postprocessed by smfix")) {
		t.Error("second pass lost the smfix marker")
	}
	_ = once
}

func TestPostProcessEmptyInput(t *testing.T) {
	// empty input cannot satisfy ExtractHeader's metadata requirements,
	// so the caller falls back to the raw file (matches production behavior:
	// "G-Code fix error(ignored)" then original content is uploaded)
	if _, err := postProcess(strings.NewReader("")); err == nil {
		t.Error("expected error for empty input")
	}
}

func TestPreprocessToOutputDir(t *testing.T) {
	dir := t.TempDir()
	old := OutputDir
	OutputDir = dir
	defer func() { OutputDir = old }()

	input := sampleGcode
	fixedPath, err := preprocessToOutputDir(strings.NewReader(input), "model.gcode", true)
	if err != nil {
		t.Fatalf("preprocessToOutputDir: %v", err)
	}
	if fixedPath == "" {
		t.Fatal("fixedPath is empty")
	}

	orig, err := os.ReadFile(filepath.Join(dir, "model.gcode"))
	if err != nil {
		t.Fatalf("original not saved: %v", err)
	}
	if string(orig) != input {
		t.Errorf("original content = %q, want %q", orig, input)
	}

	fixed, err := os.ReadFile(fixedPath)
	if err != nil {
		t.Fatalf("fixed file missing: %v", err)
	}
	if len(fixed) == 0 {
		t.Error("fixed file is empty")
	}
}

