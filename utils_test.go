func TestHumanReadableSize(t *testing.T) {
	cases := []struct {
		size int64
		want string
	}{
		{0, "0 B"},
		{512, "512 B"},
		{1023, "1023 B"},
		{1024, "1.0 KB"},
		{1536, "1.5 KB"},
		{1024 * 1024, "1.0 MB"},
		{5 * 1024 * 1024, "5.0 MB"},
		{1024 * 1024 * 1024, "1.0 GB"},
		{2 << 30, "2.0 GB"},
	}
	for _, c := range cases {
		if got := humanReadableSize(c.size); got != c.want {
			t.Errorf("humanReadableSize(%d) = %q, want %q", c.size, got, c.want)
		}
	}
}

